async function seed12BhavasGridTranslations() {
  try {
    const mongoUri = process.env.MONGODB_URI;
    if (!mongoUri) {
      console.error('MONGODB_URI not found');
      return;
    }

    console.log('Connecting to MongoDB...');
    await mongoose.connect(mongoUri, { useNewUrlParser: true, useUnifiedTopology: true });
    console.log('Connected.');

    for (const [langCode, langData] of Object.entries(BHAVAS_GRID_DATA)) {
      console.log(`Seeding 12 Bhavas of D2 Hora Chart into MongoDB for [${langCode}] - ${langData.langName}...`);
      
      await D2HoraTranslation.findOneAndUpdate(
        { lang: langCode },
        {
          $set: {
            lang: langCode,
            langName: langData.langName,
            bhavasTitles: langData.titles,
            'ui.bhavasGridTitle': langData.gridTitle,
            'ui.bhavasGridSubtitle': langData.gridSubtitle,
            'ui.houseLabel': langData.houseLabel,
            'ui.sunSignLabel': langData.sunSignLabel,
            'ui.moonSignLabel': langData.moonSignLabel,
            'ui.planetsLabel': langData.occupantsLabel,
            'ui.noneOccupants': langData.emptyLabel
          }
        },
        { upsert: true, new: true }
      );
    }

    console.log('🎉 Successfully saved 12 Bhavas of D2 Hora Chart translations into MongoDB across all Indian languages!');
    await mongoose.disconnect();
    process.exit(0);
  } catch (err) {
    console.error('Error seeding 12 Bhavas grid translations:', err);
    process.exit(1);
  }
}

seed12BhavasGridTranslations();
