async function seedD2Translations() {
  try {
    const mongoUri = process.env.MONGODB_URI;
    if (!mongoUri) {
      console.error('MONGODB_URI not found in environment');
      return;
    }

    console.log('Connecting to MongoDB...');
    await mongoose.connect(mongoUri, { useNewUrlParser: true, useUnifiedTopology: true });
    console.log('Connected to MongoDB successfully.');

    for (const item of HORA_SEEDS) {
      console.log(`Upserting D2 Hora translation for ${item.lang} (${item.langName})...`);
      await D2HoraTranslation.findOneAndUpdate(
        { lang: item.lang },
        item,
        { upsert: true, new: true }
      );
    }

    console.log('✅ Successfully seeded D2 Hora classical translations into MongoDB!');
    await mongoose.disconnect();
    process.exit(0);
  } catch (err) {
    console.error('❌ Error seeding D2 translations:', err);
    process.exit(1);
  }
}

seedD2Translations();
